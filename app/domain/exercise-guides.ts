function normalize(name: string) {
  return name.trim().toLocaleLowerCase('pl').normalize('NFD').replace(/\p{M}/gu, '').replaceAll('ł', 'l').replace(/\s+/g, ' ')
}

const guides = new Map(entries.map(([name, source, path, note]) => [normalize(name), {
  source, url: new URL(path, origins[source]).href, direct: true, note: note ?? null,
}]))

export function exerciseGuide(name: string): ExerciseGuide {
  return guides.get(normalize(name)) ?? {
    source: 'ACE', url: origins.ACE, direct: false,
    note: 'To nowe lub nierozpoznane ćwiczenie. Nie przypisano jeszcze jego instrukcji; link prowadzi do biblioteki ACE.',
  }
}
