import { execFileSync } from 'node:child_process'
import { mkdirSync, writeFileSync } from 'node:fs'
import { localContext } from './local-supabase.mjs'

try {
  localContext()
  const types = execFileSync('node_modules/.bin/supabase', ['gen', 'types', 'typescript', '--local', '--schema', 'public'], {
    encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'],
  })
  if (!types.includes('export type Database')) throw new Error('Generator nie zwrócił typów bazy.')
  mkdirSync('shared/types', { recursive: true })
  const normalized = types.replace(/[\t ]+$/gm, '').trimEnd()
  writeFileSync('shared/types/database.generated.ts', `// Generated by npm run db:types. Do not edit manually.\n${normalized}\n`)
  console.log('Wygenerowano typy z lokalnego schematu PostgreSQL.')
}
catch {
  console.error('Generowanie typów nie powiodło się. Sprawdź lokalny Supabase i Docker.')
  process.exitCode = 1
}
